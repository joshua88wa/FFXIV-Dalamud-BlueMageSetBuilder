# Regenerates BlueMageSetBuilder/Carnivale.json: the spells each Masked Carnivale stage
# calls for.
#
# Source: Blue Academy's stage guides (https://mage.blue/masked-carnivale/), from the
# site's public source at https://github.com/RoarkGit/Blue-Academy. Each guide lists
# "Required Spells" and "Recommended Spells" with {{< spell name >}} markup. This
# script keeps only the facts: which spells, whether required or recommended, and
# whether the guide offered the spell as an example ("such as ..."). No guide text is
# copied. Blue Academy is credited in the README and on the stage page in the plugin.
#
# Run it after Blue Academy updates its guides or a patch adds stages, then rebuild;
# Carnivale.json is embedded in the DLL.

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$out = Join-Path $root 'BlueMageSetBuilder\Carnivale.json'
$sourcesJson = Join-Path $root 'BlueMageSetBuilder\Sources.json'
$rawBase = 'https://raw.githubusercontent.com/RoarkGit/Blue-Academy/main/content/masked-carnivale/stages'
$pageBase = 'https://mage.blue/masked-carnivale/stages'

# Spell key ("the_rams_voice") to spellbook number, built from the English spell names
# already in Sources.json, so there is no second hand-made table to keep in step.
function ConvertTo-Key([string]$name) {
    $k = $name.ToLowerInvariant() -replace "['’]", '' -replace '[^a-z0-9]+', '_'
    return $k.Trim('_')
}

$spellByKey = @{}
$sources = Get-Content -Raw -Encoding UTF8 $sourcesJson | ConvertFrom-Json
foreach ($p in $sources.Spells.PSObject.Properties) {
    $spellByKey[(ConvertTo-Key $p.Value.Name)] = [int]$p.Name
}

$stages = [ordered]@{}
$unknown = @()
$multi = @()

foreach ($n in 1..32) {
    $nn = '{0:D2}' -f $n
    $md = [System.Text.Encoding]::UTF8.GetString((Invoke-WebRequest -UseBasicParsing -Uri "$rawBase/$nn.md" -TimeoutSec 60).RawContentStream.ToArray())
    $md = $md -replace "`r", ''

    $picks = @()
    foreach ($section in [regex]::Matches($md, '(?ms)^###\s*(Required|Recommended)\s+Spells\s*\n(.*?)(?=^###|\z)')) {
        $kind = $section.Groups[1].Value
        # List items, with their wrapped continuation lines folded in.
        $items = [regex]::Matches($section.Groups[2].Value, '(?ms)^-\s+(.*?)(?=^-\s|\z)') | ForEach-Object { $_.Groups[1].Value -replace '\s+', ' ' }
        foreach ($item in $items) {
            $keys = [regex]::Matches($item, '\{\{<\s*spell\s+([a-z0-9_]+)\s*>\}\}') | ForEach-Object { $_.Groups[1].Value }
            $example = $item -match '(?i)\bsuch as\b'
            $spells = @()
            foreach ($key in $keys) {
                if ($spellByKey.ContainsKey($key)) { $spells += $spellByKey[$key] } else { $unknown += "stage ${n}: $key" }
            }
            if ($spells.Count -eq 0) { continue }

            if ($spells.Count -gt 1) { $multi += "stage ${n} [$kind]: $item" }

            # A bullet naming several spells means one of two things, told apart by the
            # words between the spells:
            #   "or" / "like" between them: alternatives, one pick where any will do.
            #     "Ice Spikes or Schiltron"; "Saintly Beam or a Fire filler spell, such
            #     as Bomb Toss"; "1000 Needles, but other death spells like Doom".
            #   anything else: the first carries the bullet's weight and the rest are
            #     optional extras, so recommended. "Diamondback (and Mighty Guard if
            #     using safety strat)"; "Electrogenesis. Reflux can be decent ...".
            $between = [regex]::Split($item, '\{\{<\s*spell\s+[a-z0-9_]+\s*>\}\}') | Select-Object -Skip 1 | Select-Object -SkipLast 1
            $alternatives = @($between | Where-Object { $_ -match '(?i)\b(or|like)\b' }).Count -gt 0
            if ($spells.Count -gt 1 -and $alternatives) {
                $picks += [ordered]@{ Any = $spells; Kind = $kind; Example = [bool]$example }
            }
            else {
                $picks += [ordered]@{ Any = @($spells[0]); Kind = $kind; Example = [bool]$example }
                foreach ($extra in ($spells | Select-Object -Skip 1)) {
                    $picks += [ordered]@{ Any = @($extra); Kind = 'Recommended'; Example = [bool]$example }
                }
            }
        }
    }

    # Required first, then recommended, each in the guide's own order.
    $ordered = @($picks | Where-Object { $_.Kind -eq 'Required' }) + @($picks | Where-Object { $_.Kind -eq 'Recommended' })
    $stages["$n"] = [ordered]@{ Url = "$pageBase/$nn/"; Picks = $ordered }
}

$doc = [ordered]@{
    _source    = 'Blue Academy stage guides: https://mage.blue/masked-carnivale/ (source: https://github.com/RoarkGit/Blue-Academy)'
    _generated = (Get-Date -Format 'yyyy-MM-dd')
    _note      = 'Generated by tools/make-carnivale.ps1. Facts only: which spells each stage guide lists. Edit the script, not this file.'
    Stages     = $stages
}

$json = $doc | ConvertTo-Json -Depth 6
[System.IO.File]::WriteAllText($out, $json, (New-Object System.Text.UTF8Encoding($false)))

$withSpells = @($stages.Values | Where-Object { $_.Picks.Count -gt 0 }).Count
"wrote $out ($withSpells of 32 stages list spells)"
if ($unknown.Count -gt 0) { "UNMAPPED spell keys (fix ConvertTo-Key or the name): $($unknown -join ', ')" }
# Bullets with several spells are where the or/and reading matters; list them so a
# person can check the result after each regeneration.
if ($multi.Count -gt 0) { "Bullets naming several spells (check the reading):"; $multi | ForEach-Object { "  $_" } }
