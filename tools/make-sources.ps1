# Regenerates BlueMageSetBuilder/Sources.json: which creatures teach each Blue Magic
# spell, and where.
#
# The game's own data only says *where* a spell is learned (a zone or a duty), never
# which creature, so this comes from the FFXIV Online Wiki's "Blue Magic Spellbook"
# page (https://ffxiv.consolegameswiki.com/wiki/Blue_Magic_Spellbook). The script
# reads the page's source and keeps only plain facts for each source: creature, boss
# position when the wiki gives one, place, level and coordinates. No prose is copied.
#
# Run it after a patch adds spells, or whenever the wiki has been corrected. Then
# rebuild the plugin; Sources.json is embedded in the DLL.

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$out = Join-Path $root 'BlueMageSetBuilder\Sources.json'
$url = 'https://ffxiv.consolegameswiki.com/mediawiki/index.php?title=Blue_Magic_Spellbook&action=raw'

$raw = [System.Text.Encoding]::UTF8.GetString((Invoke-WebRequest -UseBasicParsing -Uri $url -TimeoutSec 60).RawContentStream.ToArray())

# Wiki markup to plain text.
function ConvertTo-Plain([string]$s) {
    $s = $s -replace '\{\{coords\|\s*([\d.]+)\s*,\s*([\d.]+)\s*\}\}', '(X:$1, Y:$2)'
    $s = $s -replace '\{\{(?:i|item icon|action icon|enemy icon)\|([^}|]+)(?:\|[^}]*)?\}\}', '$1'
    $s = $s -replace '\[\[(?:[^|\]]*\|)?([^\]]+)\]\]', '$1'
    $s = $s -replace '\{\{[^}]*\}\}', ''
    $s = $s -replace '<ref[^>]*>.*?</ref>|<ref[^>]*/>', ''
    $s = $s -replace '<[^>]+>', ''
    $s = $s -replace "'''?", ''
    # Cell styling, including the wiki's rows where the closing quote is missing.
    $s = $s -replace '^\s*style="[^|]*\|', ''
    $s = $s -replace '&amp;', '&' -replace '&nbsp;', ' '
    return ($s -replace '\s+', ' ').Trim()
}

# One "<br>" separated source, already plain, to facts.
function ConvertTo-Source([string]$text) {
    $creature = $text; $place = ''; $note = ''; $level = ''; $coords = ''

    if ($text -match '\(X:[\d.]+, Y:[\d.]+\)') { $coords = $Matches[0]; $text = $text.Replace($coords, '').Trim() }
    if ($text -match '\bLe?ve?l\.?\s*(\d+(?:\s*-\s*\d+)?)') { $level = ($Matches[1] -replace '\s', '') }

    if ($text -match '^(.*?)\s+from\s+(.+)$') {
        $creature = $Matches[1]; $place = $Matches[2]
    }
    elseif ($text -match '^(.*?)\s+-\s+(.+)$') {
        $creature = $Matches[1]
        $place = ($Matches[2] -replace '\bLe?ve?l\.?\s*\d+(\s*-\s*\d+)?\s*', '').Trim()
    }
    elseif ($text -match '^(.*?)\s+in\s+(.+)$') {
        $creature = $Matches[1]; $place = $Matches[2]
    }

    # A parenthetical on the creature is a position or a note: "(Last Boss)",
    # "(Trash before 1st Boss)", "(Lv50)".
    # There can be several, as in "Dantalion (Trash) & Phantom Knight (Trash)".
    $notes = @()
    foreach ($m in [regex]::Matches($creature, '\(([^)]*)\)')) {
        $inner = $m.Groups[1].Value.Trim()
        $lv = [regex]::Match($inner, '^(?i:lv\.?\s*)(\d+(-\d+)?)$')
        if ($lv.Success) { if (-not $level) { $level = $lv.Groups[1].Value } }
        elseif ($inner -and $notes -notcontains $inner) { $notes += $inner }
    }
    $creature = ($creature -replace '\s*\([^)]*\)', '')
    $note = $notes -join ', '

    # One spelling per position, so the plugin shows "2nd boss" everywhere.
    $note = $note -replace '(?i)\bfirst\b', '1st' -replace '(?i)\bsecond\b', '2nd' -replace '(?i)\bthird\b', '3rd' -replace '(?i)\bfinal boss\b', 'Last Boss'

    [ordered]@{
        Creature = $creature.Trim(' ', ',', '-')
        Note     = $note.Trim()
        Place    = $place.Trim(' ', ',', '-')
        Level    = $level
        Coords   = $coords
    }
}

$spells = [ordered]@{}
foreach ($row in ($raw -split "\n\|-\n")) {
    if ($row -notmatch '\{\{action icon\|([^}]+)\}\}\s*\|\|\s*(\d+)\s*\|\|') { continue }
    $number = [int]$Matches[2]
    $cells = $row -split '\|\|'
    $sources = @()
    foreach ($piece in ($cells[-1] -split '<br\s*/?>')) {
        $plain = ConvertTo-Plain $piece
        if ($plain) { $sources += ConvertTo-Source $plain }
    }
    $spells["$number"] = @{ Name = (ConvertTo-Plain $Matches[1]); Sources = $sources }
}

$doc = [ordered]@{
    _source    = 'FFXIV Online Wiki, Blue Magic Spellbook page: https://ffxiv.consolegameswiki.com/wiki/Blue_Magic_Spellbook'
    _generated = (Get-Date -Format 'yyyy-MM-dd')
    _note      = 'Generated by tools/make-sources.ps1. Plain facts only. Edit the script, not this file.'
    Spells     = $spells
}

$json = $doc | ConvertTo-Json -Depth 6
[System.IO.File]::WriteAllText($out, $json, (New-Object System.Text.UTF8Encoding($false)))
"wrote $out ($($spells.Count) spells, $(($spells.Values | ForEach-Object { $_.Sources.Count } | Measure-Object -Sum).Sum) sources)"
